-- ============================================================
-- 05_schedule_attendance.sql
-- Execute as QLSV in FREEPDB1.
-- Adds timetable and attendance tables without recreating
-- or deleting any of the existing 9 application tables.
--
-- DAY_OF_WEEK: 2=Monday, 3=Tuesday, ..., 8=Sunday.
-- START_MINUTE / END_MINUTE: minutes from 00:00.
-- CLASS_SESSIONS.SESSION_DATE is stored at midnight (DATE only).
-- Run this migration once.
-- ============================================================

-- Composite unique keys support foreign keys that enforce
-- matching class-subject and assigned teacher relationships.
ALTER TABLE classroom_subjects
    ADD CONSTRAINT uq_cs_id_teacher UNIQUE ( id, teacher_id );

ALTER TABLE student_subjects
    ADD CONSTRAINT uq_ss_id_csub UNIQUE ( id, classroom_subject_id );

-- 1. Weekly recurring timetable templates.
CREATE TABLE weekly_schedules (
    id                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                         PRIMARY KEY,
    classroom_subject_id NUMBER NOT NULL,
    day_of_week          NUMBER(1) NOT NULL,
    start_minute         NUMBER(4) NOT NULL,
    end_minute           NUMBER(4) NOT NULL,
    room                 VARCHAR2(100 CHAR),
    effective_from       DATE NOT NULL,
    effective_to         DATE,
    active               NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT fk_wsch_class_subject
        FOREIGN KEY ( classroom_subject_id )
        REFERENCES classroom_subjects ( id ),

    CONSTRAINT ck_wsch_day
        CHECK ( day_of_week BETWEEN 2 AND 8 ),

    CONSTRAINT ck_wsch_start
        CHECK ( start_minute BETWEEN 0 AND 1439 ),

    CONSTRAINT ck_wsch_end
        CHECK ( end_minute BETWEEN 1 AND 1440
               AND end_minute > start_minute ),

    CONSTRAINT ck_wsch_active
        CHECK ( active IN ( 0, 1 ) ),

    CONSTRAINT ck_wsch_effective
        CHECK ( effective_to IS NULL OR effective_to >= effective_from ),

    CONSTRAINT uq_wsch_id_csub
        UNIQUE ( id, classroom_subject_id )
);

CREATE INDEX ix_wsch_class_subject
    ON weekly_schedules ( classroom_subject_id );

-- 2. Concrete class sessions. A session may originate from a
-- weekly template or be created independently by Admin.
CREATE TABLE class_sessions (
    id                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                         PRIMARY KEY,
    weekly_schedule_id   NUMBER,
    classroom_subject_id NUMBER NOT NULL,
    session_no           NUMBER(4),
    session_date         DATE NOT NULL,
    start_minute         NUMBER(4) NOT NULL,
    end_minute           NUMBER(4) NOT NULL,
    room                 VARCHAR2(100 CHAR),
    status               VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
    note                 VARCHAR2(1000 CHAR),

    CONSTRAINT fk_cses_class_subject
        FOREIGN KEY ( classroom_subject_id )
        REFERENCES classroom_subjects ( id ),

    CONSTRAINT fk_cses_weekly_subject
        FOREIGN KEY ( weekly_schedule_id, classroom_subject_id )
        REFERENCES weekly_schedules ( id, classroom_subject_id ),

    CONSTRAINT ck_cses_date
        CHECK ( session_date = TRUNC(session_date) ),

    CONSTRAINT ck_cses_start
        CHECK ( start_minute BETWEEN 0 AND 1439 ),

    CONSTRAINT ck_cses_end
        CHECK ( end_minute BETWEEN 1 AND 1440
               AND end_minute > start_minute ),

    CONSTRAINT ck_cses_status
        CHECK ( status IN ( 'SCHEDULED', 'CANCELLED', 'COMPLETED' ) ),

    CONSTRAINT uq_cses_week_date
        UNIQUE ( weekly_schedule_id, session_date ),

    CONSTRAINT uq_cses_id_csub
        UNIQUE ( id, classroom_subject_id )
);

CREATE INDEX ix_cses_class_subject_date
    ON class_sessions ( classroom_subject_id, session_date );

CREATE INDEX ix_cses_weekly_schedule
    ON class_sessions ( weekly_schedule_id );

-- 3. Attendance: one row per enrolled student per concrete session.
-- Composite foreign keys guarantee that the student is enrolled
-- in the same class-subject as the session, and that the marking
-- teacher is the teacher assigned to that class-subject.
CREATE TABLE attendance (
    id                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                         PRIMARY KEY,
    session_id           NUMBER NOT NULL,
    classroom_subject_id NUMBER NOT NULL,
    student_subject_id   NUMBER NOT NULL,
    marked_by_teacher_id NUMBER NOT NULL,
    status               VARCHAR2(20) NOT NULL,
    note                 VARCHAR2(500 CHAR),
    marked_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT fk_att_session_subject
        FOREIGN KEY ( session_id, classroom_subject_id )
        REFERENCES class_sessions ( id, classroom_subject_id ),

    CONSTRAINT fk_att_student_subject
        FOREIGN KEY ( student_subject_id, classroom_subject_id )
        REFERENCES student_subjects ( id, classroom_subject_id ),

    CONSTRAINT fk_att_teacher_subject
        FOREIGN KEY ( classroom_subject_id, marked_by_teacher_id )
        REFERENCES classroom_subjects ( id, teacher_id ),

    CONSTRAINT ck_att_status
        CHECK ( status IN ( 'PRESENT', 'ABSENT', 'LATE', 'EXCUSED' ) ),

    CONSTRAINT uq_att_session_student
        UNIQUE ( session_id, student_subject_id )
);

CREATE INDEX ix_att_student_subject
    ON attendance ( student_subject_id );

CREATE INDEX ix_att_teacher
    ON attendance ( marked_by_teacher_id );

