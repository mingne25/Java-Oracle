-- Run as QLSV in FREEPDB1.
-- Align attendance statuses with the application business rule:
-- PRESENT = present, ABSENT = absent, LATE = late.
-- There is no separate excused-absence status.

UPDATE ATTENDANCE
SET STATUS = 'ABSENT'
WHERE STATUS = 'EXCUSED';

ALTER TABLE ATTENDANCE
    DROP CONSTRAINT CK_ATT_STATUS;

ALTER TABLE ATTENDANCE
    ADD CONSTRAINT CK_ATT_STATUS
    CHECK ( STATUS IN ( 'PRESENT', 'ABSENT', 'LATE' ) );

COMMIT;

SELECT CONSTRAINT_NAME, SEARCH_CONDITION, STATUS
FROM USER_CONSTRAINTS
WHERE TABLE_NAME = 'ATTENDANCE'
  AND CONSTRAINT_NAME = 'CK_ATT_STATUS';
