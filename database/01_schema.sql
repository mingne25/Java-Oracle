-- Execute as QLSV in FREEPDB1. Run once on an empty schema.
CREATE TABLE course_years (
    id         NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
    PRIMARY KEY,
    code       VARCHAR2(30) NOT NULL UNIQUE,
    name       VARCHAR2(120 CHAR) NOT NULL,
    start_year NUMBER(4) NOT NULL
);

CREATE TABLE faculties (
    id             NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
    PRIMARY KEY,
    code           VARCHAR2(30) NOT NULL UNIQUE,
    name           VARCHAR2(120 CHAR) NOT NULL,
    course_year_id NUMBER NOT NULL
        REFERENCES course_years ( id )
);

CREATE TABLE classrooms (
    id           NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
    PRIMARY KEY,
    code         VARCHAR2(30) NOT NULL UNIQUE,
    name         VARCHAR2(120 CHAR) NOT NULL,
    faculty_id   NUMBER NOT NULL
        REFERENCES faculties ( id ),
    max_students NUMBER(3) DEFAULT 50 NOT NULL,
    CONSTRAINT ck_class_max CHECK ( max_students = 50 )
);

CREATE TABLE subjects (
    id         NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
    PRIMARY KEY,
    code       VARCHAR2(30) NOT NULL UNIQUE,
    name       VARCHAR2(120 CHAR) NOT NULL,
    faculty_id NUMBER NOT NULL
        REFERENCES faculties ( id )
);

CREATE TABLE teachers (
    id         NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
    PRIMARY KEY,
    code       VARCHAR2(30) NOT NULL UNIQUE,
    full_name  VARCHAR2(120 CHAR) NOT NULL,
    email      VARCHAR2(255),
    faculty_id NUMBER
        REFERENCES faculties ( id )
);

CREATE TABLE students (
    id            NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
    PRIMARY KEY,
    code          VARCHAR2(30) NOT NULL UNIQUE,
    full_name     VARCHAR2(120 CHAR) NOT NULL,
    date_of_birth DATE,
    gender        VARCHAR2(20),
    email         VARCHAR2(255),
    phone         VARCHAR2(20),
    status        VARCHAR2(30) DEFAULT 'STUDYING' NOT NULL,
    classroom_id  NUMBER
        REFERENCES classrooms ( id ),
    CONSTRAINT ck_student_status
        CHECK ( status IN ( 'STUDYING', 'SUSPENDED', 'RESERVED', 'GRADUATED', 'DROPPED_OUT',
                            'EXPELLED' ) )
);

CREATE TABLE users (
    id            NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
    PRIMARY KEY,
    username      VARCHAR2(80) NOT NULL UNIQUE,
    password_hash VARCHAR2(100) NOT NULL,
    role          VARCHAR2(20) NOT NULL,
    enabled       NUMBER(1) DEFAULT 1 NOT NULL,
    student_id    NUMBER
        REFERENCES students ( id ),
    teacher_id    NUMBER
        REFERENCES teachers ( id ),
    CONSTRAINT ck_user_role
        CHECK ( role IN ( 'ADMIN', 'TEACHER', 'STUDENT' ) ),
    CONSTRAINT ck_user_link
        CHECK ( ( role = 'ADMIN'
                  AND student_id IS NULL
                  AND teacher_id IS NULL )
                OR ( role = 'TEACHER'
                     AND student_id IS NULL
                     AND teacher_id IS NOT NULL )
                OR ( role = 'STUDENT'
                     AND student_id IS NOT NULL
                     AND teacher_id IS NULL ) )
);

CREATE UNIQUE INDEX ux_user_student ON
    users (
        student_id
    );

CREATE UNIQUE INDEX ux_user_teacher ON
    users (
        teacher_id
    );

CREATE INDEX ix_student_class ON
    students (
        classroom_id
    );

CREATE INDEX ix_class_faculty ON
    classrooms (
        faculty_id
    );