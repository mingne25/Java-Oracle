-- Run once on an existing QLSV schema after database/01_schema.sql.
-- Adds class subject offerings with their assigned teacher and student enrollments.
ALTER TABLE students ADD CONSTRAINT uq_students_id_class UNIQUE ( id, classroom_id );

CREATE TABLE classroom_subjects (
    id                   NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
    PRIMARY KEY,
    classroom_id         NUMBER NOT NULL
        REFERENCES classrooms ( id ),
    subject_id           NUMBER NOT NULL
        REFERENCES subjects ( id ),
    teacher_id           NUMBER NOT NULL
        REFERENCES teachers ( id ),
    CONSTRAINT uq_classroom_subject UNIQUE ( classroom_id, subject_id ),
    CONSTRAINT uq_cls_sub_id_class UNIQUE ( id, classroom_id )
);

CREATE INDEX ix_cls_subject_teacher ON classroom_subjects ( teacher_id );

CREATE TABLE student_subjects (
    id                   NUMBER
        GENERATED BY DEFAULT ON NULL AS IDENTITY
    PRIMARY KEY,
    student_id           NUMBER NOT NULL,
    classroom_id         NUMBER NOT NULL,
    classroom_subject_id NUMBER NOT NULL,
    enrolled_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_student_class_subject UNIQUE ( student_id, classroom_subject_id ),
    CONSTRAINT fk_student_subject_student_class
        FOREIGN KEY ( student_id, classroom_id )
        REFERENCES students ( id, classroom_id ),
    CONSTRAINT fk_student_subject_class_subject
        FOREIGN KEY ( classroom_subject_id, classroom_id )
        REFERENCES classroom_subjects ( id, classroom_id )
);

CREATE INDEX ix_student_subject_student ON student_subjects ( student_id );
CREATE INDEX ix_student_subject_offering ON student_subjects ( classroom_subject_id );

